-- ============================================================================
-- 获取NPC对话
-- ============================================================================

--- 根据NPC ID和当前任务进度获取对话内容
---@param npcId string
---@param questProgress number
---@return table|nil 对话列表
function QuestData.GetDialogue(npcId, questProgress)
    local npcDialogues = QuestData.Dialogues[npcId]
    if not npcDialogues then return nil end

    -- 找当前进度或最近的低进度对话
    for p = questProgress, 0, -1 do
        if npcDialogues[p] then
            return npcDialogues[p]
        end
    end

    return nil
end

--- 获取物品信息
---@param itemId string
---@return table|nil { name, desc, hint }
function QuestData.GetItemInfo(itemId)
    return QuestData.ItemInfo[itemId]
end

return QuestData
